"""Build table_primary_quality.tex body rows from all 220 primary per-case Dice traces.

Mean over aligned cases and seeds 42--45, before the functional floor; stdlib only.
Run in the prepared workspace: python3 code/scripts/make_primary_quality_table.py
"""
import hashlib
import json
import math
from pathlib import Path
from statistics import fmean

ROOT = Path(__file__).resolve().parents[2]
PRIMARY = ROOT / "results/primary"
OUT = ROOT / "paper/generated/table_primary_quality.tex"
TASKS = ("kvasir", "acdc_lv", "brats_wt", "riga_cup", "riga_disc")
ORDER = (("dinov2_vitb14", "DINOv2-B"), ("dinov2_vits14", "DINOv2-S"), ("biomedclip", "BiomedCLIP"),
         ("clip_vitl14", "CLIP-L/14"), ("clip_vitb16", "CLIP-B/16"), ("mae_vitb16", "MAE-B"),
         ("deit_vitb16", "DeiT-B"), ("convnext_tiny", "ConvNeXt-T"), ("efficientnet_b0", "EfficientNet-B0"),
         ("resnet50", "ResNet-50"), ("resnet18", "ResNet-18"))
SEEDS = (42, 43, 44, 45)


def build():
    means, provenance, trace_hashes = {}, [], []
    saved_path = PRIMARY / "independent_check/values.json"
    saved = json.loads(saved_path.read_text())["corrected"] if saved_path.exists() else None
    for task in TASKS:
        manifest = PRIMARY / f"stats/within_cross/{task}.json"
        raw = manifest.read_bytes()
        stats = json.loads(raw)
        expected = {f"per_case_dice/{task}/{fm}/seed_{seed}.json": (fm, seed)
                    for fm, _ in ORDER for seed in SEEDS}
        sources = stats["source_files"]
        if stats["task"] != task or len(sources) != len(expected) or set(sources) != set(expected):
            raise ValueError(f"{task}: expected exactly 11 bundles x seeds 42--45")
        if set(stats["fms_available_before_floor"]) != {fm for fm, _ in ORDER}:
            raise ValueError(f"{task}: pre-floor bundle set mismatch")
        seed_means = {fm: [] for fm, _ in ORDER}
        aligned_ids = None
        for rel in sources:
            raw_trace = (PRIMARY / rel).read_bytes()
            trace = json.loads(raw_trace)
            fm, seed = expected[rel]
            if (trace["task"], trace["fm"], trace["seed"]) != (task, fm, seed):
                raise ValueError(f"{rel}: trace identity mismatch")
            ids, dice = trace["test_ids"], trace["per_case_dice"]
            n = stats["n_test"]
            if n <= 0 or trace["n_test"] != n or len(ids) != n or len(dice) != n:
                raise ValueError(f"{rel}: case count mismatch")
            if any(not isinstance(case, str) or not case for case in ids) or len(set(ids)) != n:
                raise ValueError(f"{rel}: invalid or duplicate case IDs")
            if aligned_ids is None:
                aligned_ids = ids
            if ids != aligned_ids:
                raise ValueError(f"{rel}: case IDs not aligned")
            if any(type(x) not in (int, float) or not math.isfinite(x) or not 0 <= x <= 1 for x in dice):
                raise ValueError(f"{rel}: Dice must be finite and in [0, 1]")
            seed_means[fm].append(fmean(dice))
            trace_hashes.append(f"{rel} {hashlib.sha256(raw_trace).hexdigest()}")
        means[task] = {fm: fmean(seed_means[fm]) for fm, _ in ORDER}
        if saved is not None:
            for fm, value in means[task].items():
                reference = saved[task]["bundle_mean_dice"][fm]
                if not math.isfinite(reference) or abs(value - reference) > 1e-12:
                    raise AssertionError(f"{task}/{fm}: saved bundle mean mismatch")
        provenance.append(f"% {manifest.relative_to(ROOT)} sha256={hashlib.sha256(raw).hexdigest()}")
    rows = [" & ".join([label] + [f"{means[task][fm]:.3f}" for task in TASKS]) + r" \\"
            for fm, label in ORDER]
    assert len(trace_hashes) == 220 and len(rows) == 11 and all(row.count(" & ") == 5 for row in rows)
    digest = hashlib.sha256("\n".join(sorted(trace_hashes)).encode()).hexdigest()
    header = ["% GENERATED by code/scripts/make_primary_quality_table.py; mean Dice over cases and four seeds, before floor.",
              "% Columns (lccccc): Bundle & Kvasir & ACDC & BraTS & Cup & Disc.",
              "% Sources: all 220 source_files in the five manifests below; paths relative to the primary root.",
              f"% SHA256 of sorted 'relative-path sha256' lines joined by LF (no trailing LF): {digest}"]
    body = ("\n" + r"\addlinespace[1pt]" + "\n").join(rows)
    return "\n".join(header + provenance) + "\n" + body + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print(f"wrote {OUT} (11 rows, 55 means, 220 traces)")
