"""Build current verification macros from recorded JSON and generated slice-level CIs."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VER = ROOT / "results/verification/primary"
SIDE, HIER = VER / "side_checks.json", VER / "hier_selfpair_check.json"
VERC = ROOT / "results/verification/sensitivity"
QC_CLUSTER, RESID_NULL = VERC / "values_F2d_qc_cluster.json", VERC / "values_F2c_resid_null.json"
LANE_C_TASK = {"Acdc": "acdc_lv", "Brats": "brats_wt"}
NUMS = ROOT / "paper/generated/corrected_numbers.tex"
OUT = ROOT / "paper/generated/verification_macros.tex"
SLICE_TASKS = ("Acdc", "Brats")
COLUMNS = (("Calib", "calib_gap_cluster_ci_{t}", "Gap{t}CalibSplitCI"),
           ("Beta", "beta_same_cluster_ci_{t}", "BetaSame{t}CI"),
           ("Kappa", "kappa_gap_cluster_ci_{t}", "KappaGap{t}PThirtyThreeCI"))
HIER_TASKS = ("Kvasir", "Acdc", "Brats", "Cup", "Disc")


def f3(x):
    return f"{x:.3f}"


def ci(pair):
    return f"[{f3(pair[0])}, {f3(pair[1])}]"


def slice_ci(macros, name):
    lo, hi = (float(v) for v in re.fullmatch(r"\[(-?[\d.]+), (-?[\d.]+)\]", macros[name]).groups())
    return lo, hi


def build(side, hier, macros, qc, null):
    out, ratios = {}, []
    for t in SLICE_TASKS:
        for col, key, slice_name in COLUMNS:
            lo, hi = (qc[LANE_C_TASK[t]]["beta_same_patient_cluster_ci95"] if col == "Beta" else side[key.format(t=t)])
            assert lo > 0, f"{col} {t} cluster interval does not exclude zero"
            out[f"Verif{col}ClusterCI{t}"] = ci((lo, hi))
            s_lo, s_hi = slice_ci(macros, slice_name.format(t=t))
            ratios.append((hi - lo) / (s_hi - s_lo))
    out["VerifClusterWidthRatioMin"] = f"{min(ratios):.1f}"
    out["VerifClusterWidthRatioMax"] = f"{max(ratios):.1f}"
    drops = {}
    for t in HIER_TASKS:
        keep, drop = hier[f"{t}_drop_self=False"]["ci"], hier[f"{t}_drop_self=True"]["ci"]
        assert drop[0] > 0, f"hierarchical interval without self-pairs includes zero for {t}"
        drops[t] = keep[0] - drop[0]
        out[f"VerifHierLoWithSelf{t}"], out[f"VerifHierLoNoSelf{t}"] = f3(keep[0]), f3(drop[0])
    out["VerifHierSelfPairMaxDrop"] = f3(max(drops.values()))
    out["VerifKappaGapDiscExclConstant"] = f3(side["kappa_gap_excl_constant_Disc"])
    out["VerifNConstantMembersDisc"] = str(side["n_constant_members_Disc"])
    n_perm = {v["n_perm"] for v in null.values()}
    assert len(n_perm) == 1 and all(abs(v["null_resid_mean"]) < 0.01 for v in null.values())
    out["VerifResidNullNPerm"] = str(n_perm.pop())
    return out, drops





def main():
    raw_side, raw_hier, raw_qc, raw_null = (f.read_bytes() for f in (SIDE, HIER, QC_CLUSTER, RESID_NULL))
    macros = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{([^{}]*)\}", NUMS.read_text()))
    out, drops = build(json.loads(raw_side), json.loads(raw_hier), macros, json.loads(raw_qc), json.loads(raw_null))
    head = [f"% GENERATED by {Path(__file__).resolve().relative_to(ROOT)} from verification JSON only; do not edit by hand.",
            "% Sources (sha256  path):",
            f"%   {hashlib.sha256(raw_side).hexdigest()}  {SIDE.relative_to(ROOT)}",
            f"%   {hashlib.sha256(raw_hier).hexdigest()}  {HIER.relative_to(ROOT)}",
            f"%   {hashlib.sha256(raw_qc).hexdigest()}  {QC_CLUSTER.relative_to(ROOT)}",
            f"%   {hashlib.sha256(raw_null).hexdigest()}  {RESID_NULL.relative_to(ROOT)}",
            f"%   (slice-level CIs for width ratios read from {NUMS.relative_to(ROOT)})"]
    OUT.write_text("\n".join(head + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in out.items()]) + "\n")
    # self-check: the largest self-pair drop is the task whose lower endpoint moves most
    assert out["VerifHierSelfPairMaxDrop"] == f3(max(drops.values())) and len(out) == 6 + 2 + 2 * 5 + 1 + 3
    print(f"wrote {OUT} ({len(out)} macros)")
    for k, v in out.items():
        print(f"  \\{k} = {v}")


if __name__ == "__main__":
    main()
